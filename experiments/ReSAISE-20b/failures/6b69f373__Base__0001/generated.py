# Example usage (for local testing only)
if __name__ == "__main__":
    # Simulated packet from a trusted device
    sample_payload = {"temperature": 22.5, "humidity": 45}
    # The signature would normally be generated by the device.
    # For this example we fetch it from TRUSTED_DEVICE_SIGNATURES.
    sample_sig = TRUSTED_DEVICE_SIGNATURES["device-001"]

    result = validate_device_packet("device-001", sample_sig, sample_payload)
    print("Validation successful:", result is not None)