#!/usr/bin/env python3
"""
validate_device_packet.py

This module provides a single function, ``validate_device_packet``, which
authenticates and processes data packets sent from IoT devices.

The implementation follows the recommendations for secure signature
verification:
*   Uses a constant‑time comparison (`hmac.compare_digest`) to avoid timing attacks.
*   Performs defensive checks for missing keys and malformed data.
*   Raises a ``ConnectionError`` if the packet cannot be received or is
    considered corrupted.

The function returns the original data dictionary when the signature
is verified successfully; otherwise it returns ``None``.
"""

from __future__ import annotations

import hmac
import hashlib
from typing import Dict, Optional

# Global registry of trusted device signatures.
# In a real system this would be populated from a secure source
# (e.g. a database, configuration file, or secrets manager).
TRUSTED_DEVICE_SIGNATURES: Dict[str, str] = {
    # Example entries (device_id: expected_signature)
    "device-001": "a1b2c3d4e5f678901234567890abcdef",
    "device-002": "deadbeefcafebabe1234567890abcdef",
}

def _compute_expected_signature(device_id: str, data: Dict) -> Optional[str]:
    """
    Compute the expected HMAC-SHA256 signature for a given device and payload.

    Parameters
    ----------
    device_id : str
        The unique identifier of the IoT device.
    data : dict
        The payload to sign.

    Returns
    -------
    Optional[str]
        Hex digest of the signature if a key exists for the device,
        otherwise ``None``.
    """
    # In a real deployment, each device would have its own secret key.
    # Here we simply look up the expected signature from the global
    # dictionary for demonstration purposes.
    return TRUSTED_DEVICE_SIGNATURES.get(device_id)

def validate_device_packet(
    iot_device_id: str,
    iot_signature: str,
    iot_data: Dict
) -> Optional[Dict]:
    """
    Validate an IoT device data packet.

    Parameters
    ----------
    iot_device_id : str
        Unique identifier of the sending device.
    iot_signature : str
        Cryptographic signature accompanying the packet (hex string).
    iot_data : dict
        Payload of the data packet.

    Returns
    -------
    Optional[dict]
        The original payload if signature verification succeeds,
        otherwise ``None``.

    Raises
    ------
    ConnectionError
        If the packet cannot be received or is malformed.
    """
    # Basic input validation
    if not isinstance(iot_device_id, str):
        raise ConnectionError("Invalid device ID type.")
    if not isinstance(iot_signature, str):
        raise ConnectionError("Signature must be a string.")
    if not isinstance(iot_data, dict):
        raise ConnectionError("Payload must be a dictionary.")

    # Retrieve the expected signature for this device
    expected_sig = _compute_expected_signature(iot_device_id, iot_data)
    if expected_sig is None:
        # Unknown device – treat as a connection issue
        raise ConnectionError(f"Untrusted device ID: {iot_device_id}")

    # Constant‑time comparison to mitigate timing attacks
    if not hmac.compare_digest(iot_signature.lower(), expected_sig.lower()):
        # Signature mismatch – reject the packet
        return None

    # If we reach this point, the signature is verified.
    # Additional processing could be performed here (e.g., data validation,
    # storing to a database, etc.). For now we simply return the payload.
    return iot_data

